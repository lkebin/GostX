#!/usr/bin/env python3
"""Generate the per-platform ring icon from the single source `icon/ring.svg`.

The ring glyph is used by:
  * Android  — the connect FAB (`drawable/ic_tile_vpn.xml`, a VectorDrawable)
  * macOS    — the menu bar status item (Assets.xcassets, template SVG,
               connected = full opacity, disconnected = 45 % opacity)
  * iOS      — the connect button and, later, intents (Assets.xcassets,
               template SVG)

Android cannot consume SVG at build time, and Xcode needs an asset catalog
entry, so both encodings are generated here. Run `make icon` after editing
`icon/ring.svg`; `make icon-check` verifies the committed files are in sync.

Launcher/app icons (the coloured brand artwork) are not generated here.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "icon" / "ring.svg"

ANDROID_XML = ROOT / "android/app/src/main/res/drawable/ic_tile_vpn.xml"
MACOS_ACTIVE = ROOT / "apple/macOS/Assets.xcassets/StatusBarActive.imageset"
MACOS_INACTIVE = ROOT / "apple/macOS/Assets.xcassets/StatusBarInactive.imageset"
IOS_RING = ROOT / "apple/iOS/Assets.xcassets/ConnectRing.imageset"

DO_NOT_EDIT = "Generated by `make icon` from icon/ring.svg — do not edit by hand."


def read_source() -> tuple[str, list[tuple[str, str]]]:
    """Return (viewBox, [(path_data, fill_rule), ...])."""
    svg = SOURCE.read_text()

    view_box = re.search(r'viewBox="([^"]+)"', svg)
    if not view_box:
        sys.exit(f"{SOURCE}: no viewBox found")

    paths = []
    for match in re.finditer(r"<path\b[^>]*>", svg):
        tag = match.group(0)
        data = re.search(r'\bd="([^"]+)"', tag)
        if not data:
            continue
        rule = re.search(r'fill-rule="([^"]+)"', tag)
        paths.append((data.group(1), rule.group(1) if rule else "nonzero"))

    if not paths:
        sys.exit(f"{SOURCE}: no <path> elements found")

    return view_box.group(1), paths


def android_vector(view_box: str, paths: list[tuple[str, str]]) -> str:
    _, _, width, height = view_box.split()
    body = "\n".join(
        f'    <path\n'
        f'        android:fillColor="@android:color/white"\n'
        f'        android:fillType="{"evenOdd" if rule == "evenodd" else "nonZero"}"\n'
        f'        android:pathData="{data}" />'
        for data, rule in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {DO_NOT_EDIT} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width}dp"\n'
        f'    android:height="{height}dp"\n'
        f'    android:viewportWidth="{width}"\n'
        f'    android:viewportHeight="{height}">\n'
        f"{body}\n"
        "</vector>\n"
    )


def apple_svg(paths: list[tuple[str, str]], size: int, opacity: str) -> str:
    body = "\n".join(
        f'  <path d="{data}" fill="#000000" fill-opacity="{opacity}" '
        f'fill-rule="{rule}"/>'
        for data, rule in paths
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"<!-- {DO_NOT_EDIT} -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24">\n{body}\n</svg>\n'
    )


def asset_contents(filename: str, template: bool) -> str:
    properties = {"preserve-vector-data": True}
    if template:
        properties["template-rendering-intent"] = "template"
    return json.dumps(
        {
            "images": [{"filename": filename, "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": properties,
        },
        indent=2,
    ) + "\n"


def plan(view_box: str, paths: list[tuple[str, str]]) -> dict[Path, str]:
    files: dict[Path, str] = {
        ANDROID_XML: android_vector(view_box, paths),
        MACOS_ACTIVE / "active.svg": apple_svg(paths, size=18, opacity="1"),
        MACOS_ACTIVE / "Contents.json": asset_contents("active.svg", template=True),
        MACOS_INACTIVE / "inactive.svg": apple_svg(paths, size=18, opacity="0.45"),
        MACOS_INACTIVE / "Contents.json": asset_contents("inactive.svg", template=True),
        IOS_RING / "ring.svg": apple_svg(paths, size=24, opacity="1"),
        IOS_RING / "Contents.json": asset_contents("ring.svg", template=True),
    }
    return files


def stale_files(files: dict[Path, str]) -> list[Path]:
    """Imageset members that the generator no longer produces."""
    stale: list[Path] = []
    for directory in {MACOS_ACTIVE, MACOS_INACTIVE, IOS_RING}:
        if not directory.is_dir():
            continue
        keep = {path.name for path in files if path.parent == directory}
        for existing in sorted(directory.iterdir()):
            if existing.is_file() and existing.name not in keep:
                stale.append(existing)
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if committed icons differ from the source",
    )
    args = parser.parse_args()

    files = plan(*read_source())
    stale = stale_files(files)

    if args.check:
        problems = [
            str(path.relative_to(ROOT))
            for path, content in files.items()
            if not path.exists() or path.read_text() != content
        ] + [f"{path.relative_to(ROOT)} (stale)" for path in stale]
        if problems:
            print("Icons are out of sync with icon/ring.svg:")
            for problem in problems:
                print(f"  {problem}")
            print("Run `make icon` to regenerate.")
            return 1
        print("Icons are in sync with icon/ring.svg.")
        return 0

    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")
    for path in stale:
        path.unlink()
        print(f"removed {path.relative_to(ROOT)} (stale)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())